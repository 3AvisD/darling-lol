#!/usr/bin/env python3
"""Extract the shipping vertex-descriptor reset/marking helpers verbatim, for the host model.

The model (vertex-reset-model.cpp) must exercise the code that ships, not a copy of it: this
pulls three regions out of src/Metal/MTLVertexDescriptor.mm - the item marking and the
slot-tracking decision, the reset/revoke helpers, and the reset-marks function - and writes them
as a C++ include fragment with the source line numbers in its header. It fails loudly if the
anchor comments move.

Run it before compiling the model (tools/riot-metal-bind-model/run.sh does).
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = ROOT / 'build/darling-src/src/external/metal/src/Metal/MTLVertexDescriptor.mm'
OUT = ROOT / 'build/riot-metal-bind-model/vertex-reset.extract.inc'
OUT.parent.mkdir(parents=True, exist_ok=True)

# (name, start anchor, end anchor); the end anchor is exclusive
CHUNKS = [
    ('item-marks-and-tracking', '// Marking an untouched item is harmless', 'static bool MTLVertexDescriptorResetCounters()'),
    ('reset-slots-and-revoke', 'static void MTLVertexBufferLayoutArrayResetSlots', '// The arrays used to be NSMutableDictionaries'),
    ('reset-marks', '// The reset work itself, kept in a static', '// Guest diagnosis, same shape as the bind counters'),
]

text = SOURCE.read_text().splitlines(True)
out = ['// Generated by extract-vertex-reset.py from %s. Do not edit.\n' % SOURCE.name]
for name, start_anchor, end_anchor in CHUNKS:
    start = next((i for i, line in enumerate(text) if line.startswith(start_anchor)), None)
    end = next((i for i, line in enumerate(text) if i > (start or 0) and line.startswith(end_anchor)), None)
    if start is None or end is None or end <= start:
        sys.exit('vertex-reset markers not found for %s in %s' % (name, SOURCE))
    out.append('// ---- %s (MTLVertexDescriptor.mm:%d-%d, verbatim) ----\n' % (name, start + 1, end))
    out.extend(text[start:end])
region = ''.join(out).rstrip() + '\n'
OUT.write_text(region)
print('wrote %s (%d lines)' % (OUT, region.count('\n')))
