#!/usr/bin/env python3
"""Extract the bind-tracking helpers from the Metal wrapper verbatim, for the host model.

The model test (bind-dedup-model.cpp) must exercise the code that ships, not a copy of
it: this pulls the region from `struct MTLBindObjectSlots` to the diagnostic counter out
of src/Metal/MTLRenderCommandEncoder.mm and writes it as a C++ include fragment.
Run it before compiling the model; it fails loudly if the markers moved.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = ROOT / 'build/darling-src/src/external/metal/src/Metal/MTLRenderCommandEncoder.mm'
OUT = ROOT / 'build/riot-metal-bind-model/bind-tracking.extract.inc'
OUT.parent.mkdir(parents=True, exist_ok=True)

text = SOURCE.read_text().splitlines(True)
start = next((i for i, line in enumerate(text) if line.startswith('struct MTLBindObjectSlots')), None)
end = next((i for i, line in enumerate(text) if line.startswith('// Diagnostic (guest flag /tmp/metal-debug-binds')), None)
if start is None or end is None or end <= start:
    sys.exit('bind-tracking markers not found in %s' % SOURCE)

region = ''.join(text[start:end]).rstrip() + '\n'
OUT.write_text('// Generated by extract-bind-tracking.py from %s (lines %d-%d). Do not edit.\n%s'
               % (SOURCE.name, start + 1, end, region))
print('wrote %s (%d lines)' % (OUT, region.count('\n')))
